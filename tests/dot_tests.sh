#!/usr/bin/env bash
# Sandboxed tests for ./dot. Everything happens under a temporary directory: a fake HOME,
# a fake / for /etc files, a copy of the repo, and stubs for sudo, pacman, yay, systemctl
# and `git push`. Each command runs under `env -i`, so nothing leaks in from your session.
#
#   bash tests/dot_tests.sh            run them all
#   KEEP=1 bash tests/dot_tests.sh     keep the sandbox for poking around
set -uo pipefail

SRC=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
SANDBOX=$(mktemp -d /tmp/dot-tests.XXXXXX)
[[ -n ${KEEP:-} ]] || trap 'rm -rf -- "$SANDBOX"' EXIT
PASS=0 FAIL=0 OUT=''

ok() { PASS=$((PASS + 1)); printf '  ok    %s\n' "$1"; }
fail() { FAIL=$((FAIL + 1)); printf '  FAIL  %s\n' "$1"; [[ -n ${2:-} ]] && printf '%s\n' "$2" | sed 's/^/        /' | head -40; }
check() { local name=$1; shift; if "$@"; then ok "$name"; else fail "$name" "$OUT"; fi; }
has() { grep -qF -- "$1" <<<"$OUT"; }
lacks() { ! grep -qF -- "$1" <<<"$OUT"; }
section() { printf '\n%s\n' "$*"; }

# Tree fingerprint: every path with its type, mode, link target and content hash.
# ~/.local is left out: deploy keeps its backups there.
tree_sum() {
    (cd "$1" && find . -mindepth 1 -path ./.local -prune -o -printf '%P %y %m %l\n' | LC_ALL=C sort &&
        find . -path ./.local -prune -o -type f -print0 | LC_ALL=C sort -z | xargs -0r sha256sum) | sha256sum | cut -d' ' -f1
}

# --- sandbox ---------------------------------------------------------------------------
H=$SANDBOX/home ROOT=$SANDBOX/root REPO=$SANDBOX/repo STUBS=$SANDBOX/stubs LOG=$SANDBOX/log
mkdir -p "$H" "$ROOT/etc/sddm.conf.d" "$REPO" "$STUBS" "$SANDBOX/bluerune/scripts" "$SANDBOX/bluerune/dist/profiles/joey"
: >"$LOG"
cp -r "$SRC/dot" "$SRC/lib" "$SRC/backup.sh" "$SRC/deploy.sh" "$REPO/"

cat >"$REPO/dotfiles.list" <<'EOF'
[global]
!*.bak !*-backup-*

[shell]
.bashrc
.config/fish  !fish_variables

[desktop]
.config/hypr
.config/app  !cache/
.config/systemd  nolinks !*.wants/
.config/withsecret

[bluerune]
.config/hypr/bluerune.lua

[system]
@snapshot
/etc/sddm.conf
EOF

mk() { mkdir -p -- "$(dirname -- "$H/$1")"; printf '%s\n' "$2" >"$H/$1"; }
mk .bashrc 'alias ll="ls -l"'
mk .config/fish/config.fish 'set -g fish_greeting'
mk .config/fish/fish_variables 'SETUVAR x:1'
mk .config/fish/fish_history '- cmd: secret stuff'
mk .config/hypr/hyprland.lua 'require("custom.bluerune")'
mk .config/hypr/bluerune.lua '-- Generated by BlueRune'
mk .config/hypr/hyprland.lua.bak 'old'
mk .config/hypr-backup-back-up_0908/x 'old'
mk .config/app/app.conf 'colour = blue'
mk .config/app/cache/blob 'cached'
mk .config/app/token.json '{"t": 1}'
mk .config/app/sub/deep.conf 'deep = 1'
head -c 3000 /dev/urandom | base64 >"$H/.config/app/huge.dat"
mk .config/systemd/user/foo.service '[Service]'
mkdir -p "$H/.config/systemd/user/default.target.wants"
ln -s ../foo.service "$H/.config/systemd/user/default.target.wants/foo.service"
ln -s /usr/lib/systemd/user/pipewire.service "$H/.config/systemd/user/pipewire-link.service"
mk .config/withsecret/config "github = ghp_$(printf 'A1b2C3d4%.0s' 1 2 3 4 5)"
mk .ssh/id_ed25519 'PRIVATE'
printf '[Theme]\nCurrent=astronaut\n' >"$ROOT/etc/sddm.conf"

# Stubs: each logs its arguments; sudo runs the command as the test user.
stub() { printf '#!/usr/bin/bash\n%s\n' "$2" >"$STUBS/$1"; chmod +x "$STUBS/$1"; }
stub sudo 'echo "sudo $*" >>"$LOG"; exec "$@"'
stub pacman 'echo "pacman $*" >>"$LOG"
case $1 in
  -Qqen) printf "%s\n" base git hyprland ;;
  -Qqem) printf "%s\n" yay-bin ;;
  -Qq) printf "%s\n" base git ;;
  -Slq) printf "%s\n" base git hyprland vim ;;
esac
exit 0'
stub yay 'echo "yay $*" >>"$LOG"'
stub systemctl 'echo "systemctl $*" >>"$LOG"
case "$*" in
  *list-unit-files\ --state=enabled*) [[ $1 == --user ]] && echo "foo.service enabled enabled" || echo "sddm.service enabled enabled" ;;
  *is-enabled*) exit 1 ;;
  *list-unit-files*) echo "${@: -1} disabled disabled" ;;
esac
exit 0'
stub git 'if [[ $1 == push || ($1 == -C && $3 == push) ]]; then echo "git push" >>"$LOG"; exit 0; fi; exec /usr/bin/git "$@"'
printf '#!/usr/bin/bash\necho "bluerune-installer $*" >>"$LOG"\n' >"$SANDBOX/bluerune/scripts/install-bluerune.sh"
cat >"$SANDBOX/gitconfig" <<'EOF'
[user]
	name = Test
	email = test@example.invalid
[commit]
	gpgsign = false
[init]
	defaultBranch = main
EOF

# dot ARGS... — run the repo's dot in a clean environment; output in $OUT, status in $RC.
dot() {
    OUT=$(/usr/bin/env -i HOME="$H" PATH="$STUBS:/usr/bin:/bin" TERM=dumb LANG=C.UTF-8 LOG="$LOG" \
        DOT_ROOT="$ROOT" DOT_MAX_SIZE=2k BLUERUNE_DIR="$SANDBOX/bluerune" DOT_INTERACTIVE="${INTERACTIVE:-0}" \
        GIT_CONFIG_GLOBAL="$SANDBOX/gitconfig" GIT_CONFIG_NOSYSTEM=1 \
        /usr/bin/bash "$REPO/dot" "$@" <"${STDIN:-/dev/null}" 2>&1)
    RC=$?
}
git_repo() { /usr/bin/env -i HOME="$H" PATH=/usr/bin:/bin GIT_CONFIG_GLOBAL="$SANDBOX/gitconfig" GIT_CONFIG_NOSYSTEM=1 /usr/bin/git -C "$REPO" "$@"; }
git_repo init -q && git_repo add -A && git_repo commit -qm init

# --- backup ----------------------------------------------------------------------------
section "backup"
dot backup --yes
check "backup exits 3 when it refused a secret" test "$RC" = 3
check "the planted token is reported" has 'withsecret/config'
check "the token itself is masked in the output" lacks 'A1b2C3d4A1b2C3d4'
check "the file holding the token is not copied" test ! -e "$REPO/home/.config/withsecret/config"
check "listed files are copied" test -f "$REPO/home/.bashrc" -a -f "$REPO/home/.config/app/sub/deep.conf"
check "nested entry is copied" test -f "$REPO/home/.config/hypr/bluerune.lua"
check "nested entry is listed under its own group" eval 'sed -n "/\[bluerune\]/,/\[system\]/p" <<<"$OUT" | grep -q "hypr/bluerune.lua" && ! sed -n "/\[desktop\]/,/\[bluerune\]/p" <<<"$OUT" | grep -q "hypr/bluerune.lua"'
check "entry excludes apply (cache/, fish_variables)" test ! -e "$REPO/home/.config/app/cache" -a ! -e "$REPO/home/.config/fish/fish_variables"
check "global excludes apply (*.bak, *-backup-*)" test ! -e "$REPO/home/.config/hypr/hyprland.lua.bak"
check "history and token-named files are blocked" test ! -e "$REPO/home/.config/fish/fish_history" -a ! -e "$REPO/home/.config/app/token.json"
check "files over DOT_MAX_SIZE are skipped and reported" eval '[[ ! -e $REPO/home/.config/app/huge.dat ]] && has "huge.dat is bigger"'
check "nolinks and *.wants/ keep unit symlinks out" test ! -e "$REPO/home/.config/systemd/user/default.target.wants" -a ! -L "$REPO/home/.config/systemd/user/pipewire-link.service"
check "unit files are kept" test -f "$REPO/home/.config/systemd/user/foo.service"
check "/etc entry lands in system/etc" cmp -s "$ROOT/etc/sddm.conf" "$REPO/system/etc/sddm.conf"
check "package snapshot written" test "$(paste -sd' ' "$REPO/system/packages/native.txt")" = "base git hyprland"
check "user units snapshot written" grep -qx foo.service "$REPO/system/units/user-enabled.txt"
check "backup committed" eval '[[ $(git_repo log --format=%s -1) == "Back up dotfiles"* ]]'
check "backup did not push without --push" eval '! grep -q "git push" "$LOG"'

fp=$(grep -oE '\[[0-9a-f]{12}\]' <<<"$OUT" | head -1 | tr -d '[]')
echo "$fp  # test fixture" >"$REPO/.secrets-allow"
dot backup --yes --dry-run
check "an allow-listed fingerprint is no longer reported" eval 'has "No secrets found" && has "+ home/.config/withsecret/config"'
rm -f "$REPO/.secrets-allow"
mk .config/withsecret/config 'github = nothing here'
dot backup --yes --push
check "clean backup exits 0" test "$RC" = 0
check "cleaned file is copied" test -f "$REPO/home/.config/withsecret/config"
check "--push pushes" grep -q 'git push' "$LOG"
head1=$(git_repo rev-parse HEAD)
dot backup --yes
check "second backup changes nothing" has 'The repo already matches this machine.'
check "second backup makes no commit" test "$(git_repo rev-parse HEAD)" = "$head1"

# --- status / diff ---------------------------------------------------------------------
section "status and diff"
before=$(tree_sum "$REPO")
mk .bashrc 'alias ll="ls -la"'
mk .config/app/new.conf 'new = 1'
rm "$H/.config/app/sub/deep.conf"
dot status
check "status shows a changed file" has '~ home/.bashrc'
check "status shows a file only in ~" has '+ home/.config/app/new.conf'
check "status shows a file only in the repo" has '- home/.config/app/sub/deep.conf'
check "status writes nothing" test "$(tree_sum "$REPO")" = "$before"
dot diff '~/.bashrc'
check "diff shows the changed line" eval 'has "+alias ll=\"ls -la\"" && has "-alias ll=\"ls -l\""'
dot diff .config/app
check "diff of a folder shows new files" has 'new = 1'
check "diff writes nothing" test "$(tree_sum "$REPO")" = "$before"
dot backup --yes
check "orphan-free backup picks up the changes" test -f "$REPO/home/.config/app/new.conf" -a ! -e "$REPO/home/.config/app/sub/deep.conf"

# --- deploy ----------------------------------------------------------------------------
section "deploy"
H_ORIG=$H
H=$SANDBOX/newhome
mkdir -p "$H/.config/app"
printf 'colour = red\n' >"$H/.config/app/app.conf"
printf 'mine\n' >"$H/.config/app/only-here.conf"
touch -d '2001-01-01 00:00' "$H/.config/app/app.conf"
pristine=$(tree_sum "$H")
dot deploy --all
check "deploy without --yes is a preview" has 'Nothing was written'
check "preview writes nothing" test "$(tree_sum "$H")" = "$pristine"
dot deploy --all --dry-run --yes
check "--dry-run writes nothing even with --yes" test "$(tree_sum "$H")" = "$pristine"
printf 'n\n' >"$SANDBOX/answer-no"
STDIN=$SANDBOX/answer-no INTERACTIVE=1 dot deploy --all
check "answering no writes nothing" test "$(tree_sum "$H")" = "$pristine"

dot deploy --all --yes
check "deploy writes the repo's files" cmp -s "$REPO/home/.config/app/app.conf" "$H/.config/app/app.conf"
check "deploy creates new files" test -f "$H/.bashrc" -a -f "$H/.config/hypr/bluerune.lua"
check "deploy leaves files only on the machine alone" test -f "$H/.config/app/only-here.conf"
stamp=$(ls "$H/.local/state/dotfiles/backups" | tail -1)
check "the replaced file is backed up" grep -qx 'colour = red' "$H/.local/state/dotfiles/backups/$stamp/files/.config/app/app.conf"
check "the backup has a manifest" grep -q $'^home\treplaced\t.config/app/app.conf' "$H/.local/state/dotfiles/backups/$stamp/manifest.tsv"
check "deploy did not run optional steps unasked" eval '! grep -qE "pacman -S |bluerune-installer|systemctl enable" "$LOG"'
dot deploy --all --yes
check "second deploy has nothing to do" has '0 new, 0 to replace'

dot revert "$stamp"
check "revert restores the machine byte for byte" test "$(tree_sum "$H")" = "$pristine"
dot revert "$stamp"
check "revert refuses to run twice" eval '((RC != 0))'

dot deploy --groups shell --yes
check "--groups limits the deploy" test -f "$H/.bashrc" -a ! -e "$H/.config/hypr"
dot revert --yes
check "revert with no stamp takes the latest" test "$(tree_sum "$H")" = "$pristine"

dot deploy --all --link --yes
check "--link makes symlinks into the repo" test "$(readlink "$H/.config/app/app.conf")" = "$REPO/home/.config/app/app.conf"
dot deploy --all --link --yes
check "--link is idempotent" has '0 new, 0 to replace'
dot revert --yes
check "revert after --link restores the machine" test "$(tree_sum "$H")" = "$pristine"

section "deploy steps"
: >"$LOG"
cp "$REPO/system/etc/sddm.conf" "$SANDBOX/sddm.repo"
printf '[Theme]\nCurrent=breeze\n' >"$ROOT/etc/sddm.conf"
etc_before=$(sha256sum <"$ROOT/etc/sddm.conf")
dot deploy --everything --yes
check "packages: installs missing repo packages only" grep -qx 'sudo pacman -S --needed hyprland' "$LOG"
check "packages: AUR packages go through yay" grep -qx 'yay -S --needed yay-bin' "$LOG"
check "services: enables saved units" eval 'grep -qx "sudo systemctl enable sddm.service" "$LOG" && grep -qx "systemctl --user enable foo.service" "$LOG"'
check "/etc: copies the saved file with sudo" cmp -s "$SANDBOX/sddm.repo" "$ROOT/etc/sddm.conf"
check "BlueRune installer runs with the profile" grep -q "bluerune-installer --profile $SANDBOX/bluerune/dist/profiles/joey" "$LOG"
dot revert --yes
check "revert restores the /etc file" test "$(sha256sum <"$ROOT/etc/sddm.conf")" = "$etc_before"
check "revert after the steps restores ~" test "$(tree_sum "$H")" = "$pristine"
H=$H_ORIG

# --- add -------------------------------------------------------------------------------
section "add"
mk .config/newapp/settings.ini 'size = 3'
dot add '~/.config/newapp' --group apps
check "add appends an entry under its group" grep -qx '.config/newapp' <(sed -n '/^\[apps\]/,$p' "$REPO/dotfiles.list")
mk .config/leaky/conf "OPENAI_API_KEY=sk-proj-$(printf 'Zx9Qw8Er7Ty6%.0s' 1 2 3)"
dot add '~/.config/leaky' --group apps
check "add refuses a file with a secret" eval '((RC == 3)) && ! grep -q leaky "$REPO/dotfiles.list"'
dot add '~/.ssh'
check "add refuses sensitive locations" eval '((RC != 0)) && ! grep -q ssh "$REPO/dotfiles.list"'
dot add '~/.config/newapp/settings.ini'
check "add refuses paths already covered" has 'already backed up'
mk .config/rand/conf 'seed = q8Zr3LmW9xT2vKp7Ns4Bd6Hj1Yc5Fg0Ae'
mk .config/rand/accels '(gtk_accel_path "<Actions>/ThunarBookmarks/78dc2d5f3db1e0d52fdb86cdc41e7f76" "")'
mk .config/rand/pk.txt '-----BEGIN OPENSSH PRIVATE KEY-----'
dot add '~/.config/rand' --group apps
check "a random-looking string is caught" eval '((RC == 3)) && has "high-entropy"'
check "a private key header is caught" has 'private-key'
check "path-like ids are not mistaken for secrets" lacks 'rand/accels'

section "wrappers"
OUT=$(/usr/bin/env -i HOME="$H" PATH="$STUBS:/usr/bin:/bin" TERM=dumb DOT_ROOT="$ROOT" GIT_CONFIG_GLOBAL="$SANDBOX/gitconfig" \
    DOT_MAX_SIZE=2k /usr/bin/bash "$REPO/backup.sh" --dry-run 2>&1)
check "backup.sh runs dot backup" has 'Scanning for secrets'
OUT=$(/usr/bin/env -i HOME="$H" PATH="$STUBS:/usr/bin:/bin" TERM=dumb DOT_ROOT="$ROOT" /usr/bin/bash "$REPO/deploy.sh" --dry-run --all 2>&1)
check "deploy.sh runs dot deploy" has 'Deploying (copy mode)'

printf '\n%d passed, %d failed\n' "$PASS" "$FAIL"
((FAIL == 0))
